create policy "pedido_pagamentos_insert" on public.pedido_pagamentos for insert to authenticated with check (nivel_atual() <> 'demo');
drop policy if exists "pedido_pagamentos_update" on public.pedido_pagamentos;
create policy "pedido_pagamentos_update" on public.pedido_pagamentos for update to authenticated using (nivel_atual() <> 'demo') with check (nivel_atual() <> 'demo');
drop policy if exists "pedido_pagamentos_delete" on public.pedido_pagamentos;
create policy "pedido_pagamentos_delete" on public.pedido_pagamentos for delete to authenticated using (nivel_atual() <> 'demo');

